//! The catalog: every desktop command that makes sense on a phone or a
//! tablet, as plain data.
//!
//! The ids, labels, descriptions and keywords are the desktop's (a test in
//! `kanso-app` holds the two together). Left out are the commands of a
//! window, a tab or the menu bar, and the ones that belong to a computer:
//!
//! - tabs (`next-tab`, `previous-tab`, `close-tab`, `reopen-closed-tab`,
//!   `go-to-tab-1` to `go-to-tab-9`) and windows (`open-in-new-window`);
//! - the sidebar and the zoom (`sidebar`, `zoom-in`, `zoom-out`,
//!   `actual-size`): a phone has its own navigation and the system's text
//!   size;
//! - keyboard focus and stepping (`search-list`, `go-to-list`, `next-note`,
//!   `previous-note`, `go-back`, `go-forward`);
//! - `save`, which a phone does as you type;
//! - files and the app itself (`open-file`, `quit`, `check-updates`: the
//!   stores update the apps, and `settings-updates`);
//! - the unlock with the Mac's fingerprint (`touch-id-on`, `touch-id-off`),
//!   whose words change with the computer; the phones' own biometrics
//!   arrive as their own commands;
//! - settings that are the desktop's alone (`settings-general`,
//!   `settings-plugins`, `settings-api`) and the icon themes
//!   (`settings-icon-themes`, `icon-theme`, `import-icon-theme`,
//!   `reload-icon-themes`, `settings-browse-icon-themes`), the theme files
//!   (`reload-themes`, `settings-refresh-theme-gallery`,
//!   `settings-stop-theme-preview`).

